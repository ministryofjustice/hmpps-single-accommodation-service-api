/**
 * Renders the eligibility rules graphs as a standalone, interactive HTML page using Cytoscape.js.
 *
 * The graph model is embedded as JSON; Cytoscape.js, dagre and cytoscape-dagre are loaded from a CDN.
 */
object RulesGraphHtmlRenderer {

  private val jsonMapper = JsonMapper.builder().build()

  fun render(graphs: List<RulesGraph>): String {
    val json = jsonMapper.writeValueAsString(toJson(graphs)).replace("</", "<\\/")
    return TEMPLATE.replace(DATA_PLACEHOLDER, json)
  }

  internal fun toJson(graphs: List<RulesGraph>): Map<String, Any?> = mapOf(
    "trees" to graphs.sortedBy { it.treeName }.map { graph ->
      mapOf(
        "name" to graph.treeName,
        "nodes" to graph.nodes.map { node ->
          mapOf(
            "id" to node.id,
            "title" to node.title,
            "label" to RulesGraphMarkdownRenderer.nodeLabel(node),
            "kind" to node.kind.name,
            "rules" to node.rules.map { rule ->
              mapOf(
                "className" to rule.className,
                "description" to rule.description,
                "sourcePath" to githubSourceUrl(rule.sourcePath),
              )
            },
            "onPass" to node.onPassContextUpdater?.let(::updaterJson),
            "onFail" to node.onFailContextUpdater?.let(::updaterJson),
          )
        },
        "edges" to graph.edges.map { edge ->
          mapOf("from" to edge.from, "to" to edge.to, "label" to edge.label)
        },
      )
    },
  )

  private fun updaterJson(updater: ContextUpdaterInfo): Map<String, Any?> = mapOf(
    "name" to updater.name,
    "description" to updater.description,
    "kind" to updater.kind.name,
    "sourcePath" to githubSourceUrl(updater.sourcePath),
    "outcomes" to updater.outcomes.values.map(::outcomeJson),
  )

  private fun githubSourceUrl(sourcePath: String?): String? = sourcePath?.let {
    "https://github.com/ministryofjustice/hmpps-single-accommodation-service-api/blob/main/${it.removePrefix("../")}"
  }

  private fun outcomeJson(result: ServiceResultSpec): Map<String, Any?> = mapOf(
    "status" to result.serviceStatus.name,
    "action" to result.serviceStatus.proposedAction?.let { "${it.name} (${result.serviceStatus.service.name})" },
    "linkType" to result.serviceStatus.link?.type?.name,
    "blockingReason" to result.serviceStatus.blockingStatusReason?.name,
  )

