    return '<h3>' + title + ' context updater</h3><p>' + name + esc(u.description) + '</p>' + outcomesTable(u.outcomes);
  }

  function showNode(id) {
    const n = currentTree.nodes.find(x => x.id === id);
    let html = '<h2>' + esc(n.title) + '</h2><p class="muted">' + esc(n.kind) + '</p>';
