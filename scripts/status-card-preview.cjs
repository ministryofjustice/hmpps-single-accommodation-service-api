const fs = require('node:fs')

const uiRepository = 'ministryofjustice/hmpps-single-accommodation-service-ui'
const headerPattern = /^<!-- Generated by npm run generate:status-card-preview from UI commit [a-f0-9]+\. Do not edit\. -->\r?\n/

function verifyRun(run, branch) {
  if (
    run.repository?.full_name !== uiRepository ||
    run.head_repository?.full_name !== uiRepository ||
    run.path !== '.github/workflows/pipeline.yml' ||
    run.head_branch !== branch ||
    !['push', 'workflow_dispatch'].includes(run.event) ||
    run.status !== 'completed' ||
    run.conclusion !== 'success' ||
    !/^[a-f0-9]{40}$/.test(run.head_sha)
  ) {
    throw new Error(`Artifact must come from a successful UI pipeline run on ${branch}`)
  }
}

function previewChanged(source, target, sha) {
  const generated = fs.readFileSync(source, 'utf8')
  const header = `<!-- Generated by npm run generate:status-card-preview from UI commit ${sha}. Do not edit. -->`
  if (!generated.startsWith(`${header}\n`)) {
    throw new Error('Preview header does not match the verified UI commit')
  }
  const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  return generated.replace(headerPattern, '') !== existing.replace(headerPattern, '')
}

module.exports = { verifyRun, previewChanged }

if (require.main === module) {
  const [command, ...args] = process.argv.slice(2)
  if (command === 'verify-run' && args.length === 1) {
    const run = JSON.parse(fs.readFileSync(0, 'utf8'))
    verifyRun(run, args[0])
    console.log(run.head_sha)
  } else if (command === 'preview-changed' && args.length === 3) {
    console.log(previewChanged(...args))
  } else {
    throw new Error('Usage: status-card-preview.cjs verify-run <branch> | preview-changed <source> <target> <sha>')
  }
}
