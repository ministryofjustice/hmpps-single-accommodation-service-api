const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const { test } = require('node:test')
const { previewChanged, verifyRun } = require('./status-card-preview.cjs')

const sha = 'a'.repeat(40)
const repository = { full_name: 'ministryofjustice/hmpps-single-accommodation-service-ui' }
const run = {
  repository,
  head_repository: repository,
  path: '.github/workflows/pipeline.yml',
  head_branch: 'main',
  event: 'push',
  status: 'completed',
  conclusion: 'success',
  head_sha: sha,
}
const header = revision => `<!-- Generated by npm run generate:status-card-preview from UI commit ${revision}. Do not edit. -->\n`

test('verifies successful pipeline runs on the selected branch', () => {
  assert.doesNotThrow(() => verifyRun(run, 'main'))
  assert.doesNotThrow(() => verifyRun({ ...run, head_branch: 'feature', event: 'workflow_dispatch' }, 'feature'))

  for (const invalid of [
    { ...run, head_branch: 'feature' },
    { ...run, repository: { full_name: 'other/repository' } },
    { ...run, head_repository: null },
    { ...run, path: '.github/workflows/other.yml' },
    { ...run, event: 'pull_request' },
    { ...run, status: 'in_progress' },
    { ...run, conclusion: 'failure' },
    { ...run, head_sha: 'invalid' },
  ]) {
    assert.throws(() => verifyRun(invalid, 'main'), /successful UI pipeline run/)
  }
})

test('validates the header and compares preview content independently of revision', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'status-card-preview-test-'))
  const source = path.join(dir, 'source.html')
  const target = path.join(dir, 'target.html')
  try {
    fs.writeFileSync(source, header(sha) + 'preview')
    assert.equal(previewChanged(source, target, sha), true)
    fs.writeFileSync(target, header('b'.repeat(40)) + 'preview')
    assert.equal(previewChanged(source, target, sha), false)
    fs.writeFileSync(target, header('b'.repeat(40)) + 'different')
    assert.equal(previewChanged(source, target, sha), true)
    assert.throws(() => previewChanged(source, target, 'b'.repeat(40)), /header does not match/)
    fs.writeFileSync(source, header(sha).trimEnd())
    assert.throws(() => previewChanged(source, target, sha), /header does not match/)
  } finally {
    if (fs.existsSync(source)) fs.unlinkSync(source)
    if (fs.existsSync(target)) fs.unlinkSync(target)
    fs.rmdirSync(dir)
  }
})

test('local command uses shared checks and protects local changes', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'status-card-preview-command-'))
  const directories = [
    'scripts', 'bin', 'query', 'query/src', 'query/src/main', 'query/src/main/resources',
    'query/src/main/resources/eligibility', 'docs',
  ]
  const files = [
    'scripts/update-status-card-preview.sh', 'scripts/status-card-preview.cjs', 'bin/gh', 'bin/git',
    'gradlew', 'artifact.html', 'query/src/main/resources/eligibility/status-card-preview.html', 'gradle-called',
  ]
  const file = name => path.join(dir, name)
  try {
    directories.forEach(name => fs.mkdirSync(file(name)))
    fs.copyFileSync(path.join(__dirname, 'update-status-card-preview.sh'), file(files[0]))
    fs.copyFileSync(path.join(__dirname, 'status-card-preview.cjs'), file(files[1]))
    fs.writeFileSync(file('bin/gh'), [
      '#!/usr/bin/env bash',
      'if [[ "$1" == api && "$2" == --method ]]; then echo 123',
      'elif [[ "$1" == api ]]; then printf "%s" "$RUN_JSON"',
      'elif [[ "$1" == run ]]; then',
      '  while [[ "$1" != --dir ]]; do shift; done',
      '  cp "$ARTIFACT" "$2/status-card-preview.html"',
      'fi',
    ].join('\n'), { mode: 0o755 })
    fs.writeFileSync(file('bin/git'), '#!/usr/bin/env bash\nprintf "%s" "${DIRTY:-}"\n', { mode: 0o755 })
    fs.writeFileSync(file('gradlew'), '#!/usr/bin/env bash\ntouch gradle-called\nexit "${GRADLE_EXIT:-0}"\n', { mode: 0o755 })
    fs.writeFileSync(file('artifact.html'), header(sha) + 'new')
    const target = file('query/src/main/resources/eligibility/status-card-preview.html')
    fs.writeFileSync(target, header(sha) + 'old')
    const execute = overrides => spawnSync('bash', [file(files[0]), 'feature'], {
      encoding: 'utf8',
      env: {
        ...process.env,
        PATH: `${file('bin')}:${process.env.PATH}`,
        RUN_JSON: JSON.stringify({ ...run, head_branch: 'feature' }),
        ARTIFACT: file('artifact.html'),
        ...overrides,
      },
    })

    let result = execute()
    assert.equal(result.status, 0, result.stderr)
    assert.equal(fs.readFileSync(target, 'utf8'), header(sha) + 'new')
    assert.equal(fs.existsSync(file('gradle-called')), true)
    fs.unlinkSync(file('gradle-called'))
    result = execute()
    assert.equal(result.status, 0, result.stderr)
    assert.match(result.stdout, /unchanged/)
    assert.equal(fs.existsSync(file('gradle-called')), false)
    fs.writeFileSync(file('artifact.html'), header(sha) + 'another')
    result = execute({ DIRTY: ' M docs/eligibility-rules-graph.html' })
    assert.notEqual(result.status, 0)
    assert.match(result.stderr, /local changes/)
    assert.equal(fs.readFileSync(target, 'utf8'), header(sha) + 'new')
    result = execute({ GRADLE_EXIT: '1' })
    assert.notEqual(result.status, 0)
    assert.match(result.stderr, /preview has been updated/)
  } finally {
    for (const name of files) {
      if (fs.existsSync(file(name))) fs.unlinkSync(file(name))
    }
    for (const name of directories.reverse()) fs.rmdirSync(file(name))
    fs.rmdirSync(dir)
  }
})
